export type HomeKey = keyof (typeof HOME_STRINGS)['en'];

/** Translator for the home page's v3 strings, {name} placeholders filled. */
export function homeT(lang: Lang) {
  return (key: HomeKey, vars: Record<string, string | number> = {}): string => {
    const table = (HOME_STRINGS[lang] ?? HOME_STRINGS.en) as Record<string, string>;
    const raw = table[key] ?? HOME_STRINGS.en[key];
    return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), raw);
  };
}
