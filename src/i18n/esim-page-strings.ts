export type EsimPageKey = keyof (typeof ESIM_PAGE_STRINGS)['en'];

/** Translator for the eSIM page's redesign strings, {name} placeholders filled. */
export function esimPageT(lang: Lang) {
  return (key: EsimPageKey, vars: Record<string, string | number> = {}): string => {
    const table = (ESIM_PAGE_STRINGS[lang] ?? ESIM_PAGE_STRINGS.en) as Record<string, string>;
    const raw = table[key] ?? ESIM_PAGE_STRINGS.en[key];
    return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), raw);
  };
}
