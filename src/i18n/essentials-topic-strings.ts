export type EssTopicKey = keyof (typeof ESS_TOPIC_STRINGS)['en'];

/** Translator for the essentials topic pages, English fallback; `vars` fills the {placeholders}. */
export function essTopicStrings(lang: Lang) {
  const table = (ESS_TOPIC_STRINGS as Record<string, Record<string, string>>)[lang] ?? ESS_TOPIC_STRINGS.en;
  return (key: EssTopicKey, vars: Record<string, string | number> = {}): string => {
    let s = table[key] ?? ESS_TOPIC_STRINGS.en[key];
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
