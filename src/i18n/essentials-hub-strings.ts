export type EssHubKey = keyof (typeof ESS_HUB_STRINGS)['en'];

/** Translator for the essentials hub, English fallback; `vars` fills the {placeholders}. */
export function essHubStrings(lang: Lang) {
  const table = (ESS_HUB_STRINGS as Record<string, Record<string, string>>)[lang] ?? ESS_HUB_STRINGS.en;
  return (key: EssHubKey, vars: Record<string, string | number> = {}): string => {
    let s = table[key] ?? ESS_HUB_STRINGS.en[key];
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
